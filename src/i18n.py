def normalizar_idioma(value: object) -> str:
    language = str(value).casefold().replace("_", "-").split("-", 1)[0]
    return language if language in VALID_LANGUAGES else DEFAULT_LANGUAGE


def set_language(language: str) -> None:
    global _language
    _language = normalizar_idioma(language)


def get_language() -> str:
    return _language


def tr_for(language: str, text: str, **values: Any) -> str:
    """Traduz um texto para um idioma especifico sem alterar o estado global."""

    catalog = {"en": ENGLISH, "es": SPANISH}.get(
        normalizar_idioma(language), {},
    )
    translated = catalog.get(text, text)
    return translated.format(**values) if values else translated


def tr(text: str, **values: Any) -> str:
    """Traduz um texto da interface e, opcionalmente, preenche placeholders."""

    return tr_for(_language, text, **values)
